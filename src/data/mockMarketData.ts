/**
 * Generate Event Window Timeline Points (-2h to +1d) for a given news event
 */
export function generateEventWindowPoints(event: NewsEvent): EventWindowPoint[] {
  const p0 = event.priceAtEvent;
  const p1h = event.price1hPost;
  const p1d = event.price1dPost;

  // Key event offsets: -2h, -1h, -30m, t0, +30m, +1h, +2h, +4h, +1d
  const offsets = [
    { label: '-2h', min: -120, priceMul: 0.992, mktMul: -0.15 },
    { label: '-1h', min: -60, priceMul: 0.996, mktMul: -0.08 },
    { label: '-30m', min: -30, priceMul: 0.999, mktMul: -0.02 },
    { label: 't0 (News)', min: 0, priceMul: 1.000, mktMul: 0.00 },
    { label: '+30m', min: 30, priceMul: 1 + (event.return30mPercent / 100), mktMul: event.marketReturn1hPercent * 0.6 },
    { label: '+1h', min: 60, priceMul: p1h / p0, mktMul: event.marketReturn1hPercent },
    { label: '+2h', min: 120, priceMul: 1 + ((p1h / p0 - 1) * 1.15), mktMul: event.marketReturn1hPercent * 1.2 },
    { label: '+4h', min: 240, priceMul: 1 + ((p1h / p0 - 1) * 1.25), mktMul: event.marketReturn1hPercent * 1.3 },
    { label: '+1d', min: 1440, priceMul: p1d / p0, mktMul: event.marketReturn1hPercent * 1.5 },
  ];

  const beta = COMPANY_METADATA[event.ticker]?.beta || 1.2;
  const alpha = COMPANY_METADATA[event.ticker]?.alpha || 0.05;

  let runningCAR = 0;

  return offsets.map(o => {
    const rawPrice = Number((p0 * o.priceMul).toFixed(2));
    const stockRet = Number((((rawPrice - p0) / p0) * 100).toFixed(2));
    const mktRet = Number(o.mktMul.toFixed(2));
    const expRet = Number((alpha + beta * mktRet).toFixed(2));
    const ar = Number((stockRet - expRet).toFixed(2));
    
    if (o.min >= 0) {
      runningCAR += ar * 0.5; // smooth CAR accumulation
    }

    return {
      timeOffset: o.label,
      offsetMinutes: o.min,
      rawPrice,
      stockReturnPercent: stockRet,
      marketReturnPercent: mktRet,
      expectedReturnPercent: expRet,
      abnormalReturnPercent: ar,
      cumulativeAbnormalReturnPercent: Number(runningCAR.toFixed(2)),
    };
  });
}
