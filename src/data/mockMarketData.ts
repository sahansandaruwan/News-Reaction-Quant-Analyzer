/**
 * Generate high-density intraday price series (45 granular timestamp intervals) with market microstructure metrics
 */
export function generatePriceSeries(): PricePoint[] {
  const points: PricePoint[] = [];
  const totalSteps = 45; // High density intraday intervals
  const now = new Date('2026-08-05T16:00:00Z');
  
  let nvdaPrice = 118.5;
  let msftPrice = 428.0;
  let amznPrice = 178.0;
  let googlPrice = 171.2;
  let metaPrice = 492.0;
  let aaplPrice = 219.0;
  let spyPrice = 542.0;
  let qqqPrice = 468.0;

  let cumulativeVolume = 1450000;

  for (let i = totalSteps; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 15 * 60 * 1000); // 15-min granular ticks
    const timeLabel = `${d.getHours().toString().padStart(2, '0')}:${d.getMinutes().toString().padStart(2, '0')}`;
    const timestamp = d.toISOString();
    
    // Controlled pseudo-random market walk with cross-asset correlation
    const spyReturn = (Math.sin(i * 0.3) * 0.5 + Math.cos(i * 0.6) * 0.3) * 0.008;
    spyPrice = spyPrice * (1 + spyReturn);
    qqqPrice = qqqPrice * (1 + spyReturn * 1.25);
    
    const nvdaReturn = spyReturn * COMPANY_METADATA.NVDA.beta + (Math.sin(i * 0.5) * 0.012);
    nvdaPrice = nvdaPrice * (1 + nvdaReturn);

    const msftReturn = spyReturn * COMPANY_METADATA.MSFT.beta + (Math.cos(i * 0.4) * 0.008);
    msftPrice = msftPrice * (1 + msftReturn);

    const amznReturn = spyReturn * COMPANY_METADATA.AMZN.beta + (Math.sin(i * 0.2) * 0.009);
    amznPrice = amznPrice * (1 + amznReturn);

    const googlReturn = spyReturn * COMPANY_METADATA.GOOGL.beta + (Math.cos(i * 0.3) * 0.007);
    googlPrice = googlPrice * (1 + googlReturn);

    const metaReturn = spyReturn * COMPANY_METADATA.META.beta + (Math.sin(i * 0.4) * 0.011);
    metaPrice = metaPrice * (1 + metaReturn);

    const aaplReturn = spyReturn * COMPANY_METADATA.AAPL.beta + (Math.cos(i * 0.2) * 0.005);
    aaplPrice = aaplPrice * (1 + aaplReturn);

    // Microstructure density metrics
    const stepVolume = Math.floor(180000 + Math.abs(Math.sin(i * 0.8)) * 420000);
    cumulativeVolume += stepVolume;
    const orderFlowImbalance = Number((Math.sin(i * 0.7) * 0.85).toFixed(2));
    const bidAskSpreadBps = Number((1.2 + Math.abs(Math.cos(i * 0.9)) * 2.8).toFixed(1));
    const impliedVolVXN = Number((21.5 + Math.sin(i * 0.4) * 4.2).toFixed(1));
    const vwap = Number((nvdaPrice * 0.998).toFixed(2));

    points.push({
      timestamp,
      timeLabel,
      NVDA: Number(nvdaPrice.toFixed(2)),
      MSFT: Number(msftPrice.toFixed(2)),
      AMZN: Number(amznPrice.toFixed(2)),
      GOOGL: Number(googlPrice.toFixed(2)),
      META: Number(metaPrice.toFixed(2)),
      AAPL: Number(aaplPrice.toFixed(2)),
      SPY: Number(spyPrice.toFixed(2)),
      QQQ: Number(qqqPrice.toFixed(2)),
      volume: stepVolume,
      vwap,
      orderFlowImbalance,
      bidAskSpreadBps,
      impliedVolVXN,
    });
  }

  return points;
}

